#!/usr/bin/env node
// Builds lib/prompts.gen.ts from docs/prompts/*.md, the source of truth for the agent prompts.
//
//   node scripts/prompts.mjs           regenerate lib/prompts.gen.ts
//   node scripts/prompts.mjs --check   exit 1 when lib/prompts.gen.ts differs from a fresh build
//
// Each prompt file is front matter (`id`, `title`, `when`, one line each) followed by the body.
// The body may use only the placeholders {{endpoint}}, {{repo}} and {{org}}; anything else
// fails the build, so a typo never reaches a user. The output is a pure function of the files
// (sorted by file name), so `gen:check` is stable.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(web, "..", "..", "docs", "prompts");
const target = join(web, "lib", "prompts.gen.ts");
const PLACEHOLDERS = new Set(["endpoint", "repo", "org"]);
const KEYS = ["id", "title", "when"];

function fail(file, message) {
  console.error(`prompts: docs/prompts/${file}: ${message}`);
  process.exit(1);
}

function parse(file, text) {
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text.replace(/\r\n/g, "\n"));
  if (!match) fail(file, "missing front matter (--- id, title, when ---)");
  const meta = {};
  for (const line of match[1].split("\n")) {
    const kv = /^([a-z]+):\s*(.+)$/.exec(line);
    if (!kv) fail(file, `front matter line is not "key: value": ${line}`);
    if (!KEYS.includes(kv[1])) fail(file, `unknown front matter key "${kv[1]}"`);
    meta[kv[1]] = kv[2].trim();
  }
  for (const key of KEYS) if (!meta[key]) fail(file, `front matter has no "${key}"`);
  const id = file.replace(/\.md$/, "");
  if (meta.id !== id) fail(file, `id "${meta.id}" must equal the file name "${id}"`);
  const body = match[2].trim();
  if (!body) fail(file, "the body is empty");
  for (const [, name] of body.matchAll(/\{\{([^{}]*)\}\}/g)) {
    if (!PLACEHOLDERS.has(name)) fail(file, `unknown placeholder {{${name}}} (allowed, without spaces: endpoint, repo, org)`);
  }
  return { id: meta.id, title: meta.title, when: meta.when, body };
}

function render() {
  const files = readdirSync(source)
    .filter((n) => n.endsWith(".md"))
    .sort();
  if (!files.length) fail("", "no prompt files found");
  const prompts = files.map((f) => parse(f, readFileSync(join(source, f), "utf8")));
  const ids = new Set(prompts.map((p) => p.id));
  if (ids.size !== prompts.length) fail("", "duplicate ids");
  const items = prompts
    .map(
      (p) =>
        `  {\n    id: ${JSON.stringify(p.id)},\n    title: ${JSON.stringify(p.title)},\n    when: ${JSON.stringify(p.when)},\n    body: ${JSON.stringify(p.body)},\n  },`,
    )
    .join("\n");
  return `// Generated by scripts/prompts.mjs from docs/prompts/*.md. Do not edit: run \`bun run gen\`.\nexport const GENERATED_PROMPTS: { id: string; title: string; when: string; body: string }[] = [\n${items}\n];\n`;
}

const next = render();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // A missing file is stale too.
  }
  if (current !== next) {
    console.error("lib/prompts.gen.ts is stale: run `bun run gen` and commit it.");
    process.exit(1);
  }
  console.log("lib/prompts.gen.ts is up to date.");
} else {
  writeFileSync(target, next);
  console.log(`wrote lib/prompts.gen.ts (${next.split("\n  {").length - 1} prompts)`);
}
