export type IconName = keyof typeof ICONS;
export type { IconWeight };

/** Decorative by default (`aria-hidden`); pass `aria-label` and `aria-hidden={false}` to label one. */
export function Icon({ name, size = 16, weight = "regular", className, ...rest }: { name: IconName; size?: number; weight?: IconWeight } & Omit<SVGProps<SVGSVGElement>, "name" | "ref">) {
  const Glyph = ICONS[name];
  return <Glyph size={size} weight={weight} aria-hidden="true" focusable="false" data-icon={name} className={className ? "shrink-0 " + className : "shrink-0"} {...rest} />;
}
