type Leaf = string | number | boolean | null | undefined;
type AllTrue<R> = [R[keyof R]] extends [true] ? true : false;

/** True when every key of V exists in J and each value conforms, recursively. */
export type Conforms<V, J> = [V] extends [Leaf]
  ? [V] extends [J] ? true : false
  : [V] extends [readonly (infer VE)[]]
    ? [NonNullable<J>] extends [readonly (infer JE)[]] ? Conforms<VE, JE> : false
    : [Exclude<keyof V, keyof NonNullable<J>>] extends [never]
      ? AllTrue<{ [K in keyof V]-?: Conforms<NonNullable<V[K]>, NonNullable<NonNullable<J>[K & keyof NonNullable<J>]>> }>
      : false;

type Check<T extends true> = T;

