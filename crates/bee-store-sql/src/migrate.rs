//! The versioned schema migrations, shared by both backends and applied at open.
//!
//! Each migration is one embedded SQL file written once for both databases; a handful of
//! tokens (`{KEY}`, `{BLOB}`, `{TEXT}`, `{WITHOUT_ROWID}`) are replaced per dialect. The
//! `bee_schema` table records every applied version with a digest of its rendered SQL, so a
//! store refuses to open a database whose history differs from the binary's or that was
//! migrated by a newer binary.

use bee_core::{BeeError, Reason, hex};

use crate::backend::Dialect;

/// One schema migration.
#[derive(Clone, Copy, Debug)]
pub struct Migration {
    /// Version number; versions start at 1 and increase by one.
    pub version: i64,
    /// Short name.
    pub name: &'static str,
    /// The SQL, with dialect tokens.
    pub sql: &'static str,
}

/// Every migration this binary knows, in order.
pub const MIGRATIONS: &[Migration] = &[Migration {
    version: 1,
    name: "init",
    sql: include_str!("../migrations/0001_init.sql"),
}];

/// The schema version this binary writes.
pub fn latest_version() -> i64 {
    MIGRATIONS.last().map(|m| m.version).unwrap_or(0)
}

/// SQL that creates the version table when missing.
pub(crate) fn schema_table_sql(d: Dialect) -> String {
    render(
        "CREATE TABLE IF NOT EXISTS bee_schema (\n    version BIGINT PRIMARY KEY,\n    name {TEXT} NOT NULL,\n    digest {TEXT} NOT NULL\n)",
        d,
    )
}

/// The migration's SQL for one dialect.
pub(crate) fn render(sql: &str, d: Dialect) -> String {
    let (key, blob, text, without_rowid) = match d {
        Dialect::Postgres => (
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            "BYTEA",
            "TEXT COLLATE \"C\"",
            "",
        ),
        Dialect::Sqlite => ("INTEGER PRIMARY KEY", "BLOB", "TEXT", "WITHOUT ROWID"),
    };
    sql.replace("{KEY}", key)
        .replace("{BLOB}", blob)
        .replace("{TEXT}", text)
        .replace("{WITHOUT_ROWID}", without_rowid)
}

/// Digest of the rendered SQL, recorded with the version.
pub(crate) fn digest(rendered: &str) -> String {
    hex::encode(&bee_object::digest(rendered.as_bytes()))
}

/// Decides which migrations to apply given the recorded `(version, digest)` rows.
pub(crate) fn pending(
    applied: &[(i64, String)],
    d: Dialect,
) -> Result<Vec<(Migration, String)>, BeeError> {
    let latest = latest_version();
    let mut out = Vec::new();
    for (version, _) in applied {
        if *version > latest {
            return Err(BeeError::new(
                Reason::Unavailable,
                format!(
                    "metadata schema is at version {version}, newer than this binary's {latest}"
                ),
            )
            .with_retryable(false));
        }
    }
    for m in MIGRATIONS {
        let rendered = render(m.sql, d);
        let want = digest(&rendered);
        match applied.iter().find(|(v, _)| *v == m.version) {
            Some((_, got)) if *got == want => {}
            Some(_) => {
                return Err(BeeError::new(
                    Reason::Internal,
                    format!(
                        "metadata schema migration {} ({}) differs from this binary's",
                        m.version, m.name
                    ),
                ));
            }
            None => out.push((*m, rendered)),
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn versions_are_dense_and_tokens_all_replaced() {
        for (i, m) in MIGRATIONS.iter().enumerate() {
            assert_eq!(m.version, i as i64 + 1);
            for d in [Dialect::Postgres, Dialect::Sqlite] {
                let r = render(m.sql, d);
                assert!(!r.contains('{'), "{d:?} left a token in {}", m.name);
            }
        }
        assert!(render("x {BLOB}", Dialect::Postgres).ends_with("BYTEA"));
        assert!(render("x {BLOB}", Dialect::Sqlite).ends_with("BLOB"));
    }

    #[test]
    fn pending_checks_history() {
        let d = Dialect::Sqlite;
        let all = pending(&[], d).unwrap();
        assert_eq!(all.len(), MIGRATIONS.len());
        let done: Vec<(i64, String)> = all.iter().map(|(m, r)| (m.version, digest(r))).collect();
        assert!(pending(&done, d).unwrap().is_empty());
        let tampered = vec![(1, "00".to_string())];
        assert_eq!(pending(&tampered, d).unwrap_err().reason, Reason::Internal);
        let newer = vec![(latest_version() + 1, "x".to_string())];
        let e = pending(&newer, d).unwrap_err();
        assert_eq!(e.reason, Reason::Unavailable);
        assert!(!e.retryable);
    }
}
