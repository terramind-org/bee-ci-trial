//! Matrix expansion (`jobs.<id>.strategy.matrix`).
//!
//! GitHub's documented algorithm:
//!
//! 1. The cartesian product of every vector, first key outermost
//!    (`os: [a, b]`, `node: [1, 2]` gives `a/1, a/2, b/1, b/2`).
//! 2. `exclude` removes each combination that matches every key of an entry.
//! 3. Each `include` entry is merged into every original combination whose original keys it
//!    does not contradict; keys added by an earlier include may be overwritten, original values
//!    never. An entry that merges into no combination becomes a new combination. Combinations
//!    created by `include` are never merged into.
//! 4. At most 256 combinations.
//!
//! Matrix keys are case-insensitive.

use crate::value::{Object, Value, eq_ignore_case};

/// GitHub's limit on jobs generated by one matrix.
pub const MAX_MATRIX_JOBS: usize = 256;

/// Why a matrix could not be expanded.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum MatrixError {
    /// The matrix is malformed.
    Invalid(String),
    /// More than [`MAX_MATRIX_JOBS`] combinations (the count, or a lower bound when huge).
    TooLarge(u64),
}

impl std::fmt::Display for MatrixError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            MatrixError::Invalid(m) => f.write_str(m),
            MatrixError::TooLarge(n) => write!(
                f,
                "Strategy matrix produces {n} jobs, more than the maximum of {MAX_MATRIX_JOBS}"
            ),
        }
    }
}

/// The number of combinations of the vectors alone (before exclude and include), saturating.
pub fn product_size(matrix: &Object) -> u64 {
    let mut any = false;
    let mut n: u64 = 1;
    for (k, v) in matrix.iter() {
        if eq_ignore_case(k, "include") || eq_ignore_case(k, "exclude") {
            continue;
        }
        any = true;
        let len = v.as_array().map_or(0, <[Value]>::len) as u64;
        n = n.saturating_mul(len);
    }
    if any { n } else { 0 }
}

fn entries<'a>(matrix: &'a Object, key: &str) -> Result<Vec<&'a Object>, MatrixError> {
    match matrix.iter().find(|(k, _)| eq_ignore_case(k, key)) {
        None | Some((_, Value::Null)) => Ok(Vec::new()),
        Some((_, Value::Array(items))) => items
            .iter()
            .map(|i| {
                i.as_object().ok_or_else(|| {
                    MatrixError::Invalid(format!("matrix '{key}' entries must be mappings"))
                })
            })
            .collect(),
        Some(_) => Err(MatrixError::Invalid(format!(
            "matrix '{key}' must be a sequence of mappings"
        ))),
    }
}

/// Expands an evaluated matrix into its combinations, in GitHub's order.
pub fn expand(matrix: &Value) -> Result<Vec<Object>, MatrixError> {
    let Some(matrix) = matrix.as_object() else {
        return Err(MatrixError::Invalid(format!(
            "the matrix must be a mapping, found {}",
            matrix.to_display_string()
        )));
    };
    let mut vectors: Vec<(&str, &[Value])> = Vec::new();
    for (k, v) in matrix.iter() {
        if eq_ignore_case(k, "include") || eq_ignore_case(k, "exclude") {
            continue;
        }
        match v.as_array() {
            Some([]) => {
                return Err(MatrixError::Invalid(format!(
                    "Matrix vector '{k}' does not contain any values"
                )));
            }
            Some(items) => vectors.push((k, items)),
            None => {
                return Err(MatrixError::Invalid(format!(
                    "Matrix vector '{k}' must be a sequence"
                )));
            }
        }
    }
    let excludes = entries(matrix, "exclude")?;
    let includes = entries(matrix, "include")?;
    for e in &excludes {
        for (k, _) in e.iter() {
            if !vectors.iter().any(|(vk, _)| eq_ignore_case(vk, k)) {
                return Err(MatrixError::Invalid(format!(
                    "Matrix exclude key '{k}' does not match any key within the matrix"
                )));
            }
        }
    }
    let size = product_size(matrix);
    // Exclusions can shrink a large product, but never by more than one combination per
    // entry for fully specified entries; bound the work before materialising.
    if size > 1_000_000 {
        return Err(MatrixError::TooLarge(size));
    }
    let mut combos: Vec<Object> = if vectors.is_empty() {
        Vec::new()
    } else {
        let mut out = vec![Object::new()];
        for (k, items) in &vectors {
            let mut next = Vec::with_capacity(out.len() * items.len());
            for c in &out {
                for v in *items {
                    let mut c2 = c.clone();
                    c2.insert(*k, v.clone());
                    next.push(c2);
                }
            }
            out = next;
        }
        out
    };
    combos.retain(|c| {
        !excludes.iter().any(|e| {
            e.iter()
                .all(|(k, v)| c.get(k).is_some_and(|cv| value_matches(cv, v)))
        })
    });
    let original = combos.len();
    let is_vector_key = |k: &str| vectors.iter().any(|(vk, _)| eq_ignore_case(vk, k));
    for inc in &includes {
        let mut merged = false;
        for c in combos.iter_mut().take(original) {
            let compatible = inc
                .iter()
                .filter(|(k, _)| is_vector_key(k))
                .all(|(k, v)| c.get(k).is_some_and(|cv| cv == v));
            if compatible {
                for (k, v) in inc.iter() {
                    c.insert(k, v.clone());
                }
                merged = true;
            }
        }
        if !merged {
            combos.push((*inc).clone());
        }
    }
    if combos.len() > MAX_MATRIX_JOBS {
        return Err(MatrixError::TooLarge(combos.len() as u64));
    }
    Ok(combos)
}

/// Whether a combination value matches an exclude value: equal, or for objects every key of
/// the exclude value matches.
fn value_matches(actual: &Value, wanted: &Value) -> bool {
    match (actual, wanted) {
        (Value::Object(a), Value::Object(w)) => w
            .iter()
            .all(|(k, wv)| a.get(k).is_some_and(|av| value_matches(av, wv))),
        _ => actual == wanted,
    }
}

/// The suffix GitHub appends to a matrix job's display name: the values, comma-separated.
pub fn display_values(combo: &Object) -> String {
    combo
        .iter()
        .map(|(_, v)| match v {
            Value::Array(_) | Value::Object(_) => v.to_json_compact(),
            other => other.to_display_string(),
        })
        .collect::<Vec<_>>()
        .join(", ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::value::parse_json;

    fn exp(json: &str) -> Vec<String> {
        expand(&parse_json(json).unwrap())
            .unwrap()
            .iter()
            .map(|c| Value::from(c.clone()).to_json_compact())
            .collect()
    }

    #[test]
    fn cartesian_product_first_key_outermost() {
        assert_eq!(
            exp(r#"{"os":["a","b"],"node":[1,2]}"#),
            vec![
                r#"{"os":"a","node":1}"#,
                r#"{"os":"a","node":2}"#,
                r#"{"os":"b","node":1}"#,
                r#"{"os":"b","node":2}"#
            ]
        );
    }

    #[test]
    fn documented_include_example() {
        // "Expanding or adding matrix configurations" in GitHub's matrix docs.
        let got = exp(
            r#"{"fruit":["apple","pear"],"animal":["cat","dog"],"include":[
                {"color":"green"},
                {"color":"pink","animal":"cat"},
                {"fruit":"apple","shape":"circle"},
                {"fruit":"banana"},
                {"fruit":"banana","animal":"cat"}]}"#,
        );
        assert_eq!(
            got,
            vec![
                r#"{"fruit":"apple","animal":"cat","color":"pink","shape":"circle"}"#,
                r#"{"fruit":"apple","animal":"dog","color":"green","shape":"circle"}"#,
                r#"{"fruit":"pear","animal":"cat","color":"pink"}"#,
                r#"{"fruit":"pear","animal":"dog","color":"green"}"#,
                r#"{"fruit":"banana"}"#,
                r#"{"fruit":"banana","animal":"cat"}"#,
            ]
        );
    }

    #[test]
    fn documented_exclude_example() {
        // "Excluding matrix configurations": os x version x environment minus two.
        let got = exp(
            r#"{"os":["macos-latest","windows-latest"],"version":[12,14,16],"environment":["staging","production"],
                "exclude":[{"os":"macos-latest","version":12,"environment":"production"},{"os":"windows-latest","version":16}]}"#,
        );
        assert_eq!(got.len(), 12 - 1 - 2);
        assert!(
            !got.iter()
                .any(|c| c.contains("windows-latest") && c.contains(":16"))
        );
    }

    #[test]
    fn include_only_matrix() {
        assert_eq!(
            exp(
                r#"{"include":[{"site":"production","datacenter":"site-a"},{"site":"staging","datacenter":"site-b"}]}"#
            ),
            vec![
                r#"{"site":"production","datacenter":"site-a"}"#,
                r#"{"site":"staging","datacenter":"site-b"}"#
            ]
        );
    }

    #[test]
    fn include_extends_specific_combination() {
        // "Example: Expanding configurations": node 16 on windows gets npm 6.
        let got = exp(
            r#"{"os":["windows-latest","ubuntu-latest"],"node":[14,16],"include":[{"os":"windows-latest","node":16,"npm":6}]}"#,
        );
        assert_eq!(got[1], r#"{"os":"windows-latest","node":16,"npm":6}"#);
        assert_eq!(got.len(), 4);
    }

    #[test]
    fn exclude_matches_object_values_partially() {
        let got = exp(r#"{"t":[{"a":1,"b":2},{"a":3,"b":4}],"exclude":[{"t":{"a":1}}]}"#);
        assert_eq!(got, vec![r#"{"t":{"a":3,"b":4}}"#]);
    }

    #[test]
    fn errors() {
        let e = |j: &str| expand(&parse_json(j).unwrap()).unwrap_err();
        assert!(
            matches!(e(r#"{"os":[]}"#), MatrixError::Invalid(m) if m.contains("does not contain any values"))
        );
        assert!(matches!(e(r#"{"os":"x"}"#), MatrixError::Invalid(_)));
        assert!(matches!(
            e(r#"{"os":["a"],"exclude":[{"node":1}]}"#),
            MatrixError::Invalid(_)
        ));
        assert!(matches!(e(r#"{"include":"x"}"#), MatrixError::Invalid(_)));
        assert!(matches!(e("[1]"), MatrixError::Invalid(_)));
        let big = format!(
            r#"{{"a":{0},"b":{0},"c":[1,2,3]}}"#,
            Value::array((0..10).map(|i| Value::Number(f64::from(i)))).to_json_compact()
        );
        assert_eq!(e(&big), MatrixError::TooLarge(300));
        let ok = format!(
            r#"{{"a":{0},"b":{0}}}"#,
            Value::array((0..16).map(|i| Value::Number(f64::from(i)))).to_json_compact()
        );
        assert_eq!(expand(&parse_json(&ok).unwrap()).unwrap().len(), 256);
    }

    #[test]
    fn keys_are_case_insensitive() {
        assert_eq!(
            exp(r#"{"OS":["a"],"include":[{"os":"a","x":1}]}"#),
            vec![r#"{"OS":"a","x":1}"#]
        );
    }

    #[test]
    fn display_suffix() {
        let c = expand(
            &parse_json(
                r#"{"os":["ubuntu-latest"],"node":[18],"include":[{"experimental":true}]}"#,
            )
            .unwrap(),
        )
        .unwrap();
        assert_eq!(display_values(&c[0]), "ubuntu-latest, 18, true");
    }
}
